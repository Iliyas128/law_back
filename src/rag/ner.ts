const CRIMINAL_RE = /уголовн|преступлен|убийств|кражу|грабёж|разбо|мошенничеств(?!а\s+коап)|следовател|обвиняем/i;
const ADMIN_RE = /административн|коап|правонаруш|мрп|инспектор\s+дпс|протокол\s+об\s+админ/i;
const ARTICLE_RE =
  /(?:статья|статьи|статью|ст\.?|бап)\s*№?\s*(\d{1,4}(?:-\d+)?)|№\s*(\d{1,4}(?:-\d+)?)\s*(?:коап|ук|упк|нк|тк|гк|гпк)?/i;

export function extractQueryEntities(question: string): QueryEntities {
  const q = question.trim();

  const articleMatch = q.match(ARTICLE_RE);
  const articleNumber = articleMatch?.[1] ?? articleMatch?.[2] ?? null;

  const laws: LawCode[] = [];
  const enrichment: string[] = [];

  for (const { code, re, terms } of LAW_PATTERNS) {
    if (re.test(q)) {
      laws.push(code);
      enrichment.push(...terms);
    }
  }

  const topics: TopicTag[] = [];
  for (const { tag, re, terms } of TOPIC_PATTERNS) {
    if (re.test(q)) {
      topics.push(tag);
      enrichment.push(...terms);
    }
  }

  const isCriminal = CRIMINAL_RE.test(q) && !ADMIN_RE.test(q);
  const isAdmin = ADMIN_RE.test(q) || (!isCriminal && topics.includes("fine"));

  // Темы, по которым ВСЕГДА нужен УК (даже если он явно не упомянут)
  const criminalTopics: TopicTag[] = [
    "battery",
    "health_harm",
    "criminal_hooliganism",
    "theft",
    "drugs",
    "weapon",
    "sexual",
    "death",
  ];
  if (topics.some((t) => criminalTopics.includes(t)) && !laws.includes("uk")) {
    laws.push("uk");
    enrichment.push(...LAW_PATTERNS.find((p) => p.code === "uk")!.terms);
  }

  // Бытовая драка / повреждения / опьянение часто пересекаются с КоАП
  if (
    (topics.includes("battery") ||
      topics.includes("health_harm") ||
      topics.includes("criminal_hooliganism") ||
      topics.includes("alcohol")) &&
    !laws.includes("koap")
  ) {
    laws.push("koap");
    enrichment.push(...LAW_PATTERNS.find((p) => p.code === "koap")!.terms);
  }

  // Эвристическая до-разметка кодексов: если ничего не угадали, но есть тема
  if (laws.length === 0) {
    if (isAdmin || topics.includes("police_stop") || topics.includes("witness")) {
      laws.push("koap");
      enrichment.push(...LAW_PATTERNS.find((p) => p.code === "koap")!.terms);
    }
    if (topics.includes("documents") || topics.includes("detention") || topics.includes("search")) {
      laws.push("police");
      enrichment.push(...LAW_PATTERNS.find((p) => p.code === "police")!.terms);
    }
    if (topics.includes("alcohol") || topics.includes("police_stop")) {
      laws.push("pdd");
      enrichment.push(...LAW_PATTERNS.find((p) => p.code === "pdd")!.terms);
    }
  }

  const asksAboutLiability =
    topics.includes("fine") ||
    /\b(что\s+(?:мне\s+)?будет|чем\s+это\s+грозит|какое\s+наказан|какой\s+штраф|сколько\s+штраф)\b/i.test(
      q,
    );

  // Дедупликация
  const dedupedLaws = Array.from(new Set(laws));
  const dedupedTopics = Array.from(new Set(topics));
  enrichment.push(...enrichHarmSeverityLegalTerms(q));

  const dedupedTerms = Array.from(new Set(enrichment));

  return {
    articleNumber,
    laws: dedupedLaws,
    topics: dedupedTopics,
    asksAboutLiability,
    isAdmin,
    isCriminal,
    enrichmentTerms: dedupedTerms,
  };
}

/** Сопоставление law-строки чанка с кодом закона из NER. */
export function lawMatchesCode(chunkLaw: string, code: LawCode): boolean {
  const s = chunkLaw.toLowerCase();
  switch (code) {
    case "koap":
      return /административн|коап|админ\.?\s*правонаруш/.test(s);
    case "uk":
      return /уголовн\w*\s+кодекс|^ук\b|\bук\s+рк\b/.test(s) && !/процесс/.test(s);
    case "upk":
      return /уголовно-процессуальн|^упк\b|\bупк\s+рк\b/.test(s);
    case "constitution":
      return /конституц/.test(s);
    case "police":
      return /полици|органах\s+внутренних\s+дел|овд\b/.test(s);
    case "pdd":
      return /дорожн|пдд|правила\s+дорожн/.test(s);
    case "tax":
      return /налогов/.test(s);
    case "labor":
      return /трудов/.test(s);
    case "civil":
      return /гражданск\w*\s+кодекс|^гк\b/.test(s) && !/процесс/.test(s);
    case "civilProc":
      return /гражданск\w*\s+процесс|^гпк\b/.test(s);
    default:
      return false;
  }
}

/**
 * Полная строка для эмбеддинга/лексики: оригинал + эвристические термины + NER-термины.
 * Используется как «обогащённый» запрос для retrieval.
 */
export function buildRetrievalQuery(question: string, entities: QueryEntities): string {
  const lines: string[] = [question.trim()];
  if (entities.enrichmentTerms.length > 0) {
    lines.push(entities.enrichmentTerms.join(" "));
  }
  if (entities.articleNumber) {
    lines.push(`статья ${entities.articleNumber}`);
  }
  return lines.join("\n");
}
