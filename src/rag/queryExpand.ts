/**
 * Дополняет пользовательский вопрос нейтральными юридическими терминами для эмбеддинга/лексики,
 * чтобы коллоквиальные формулировки лучше попадали в релевантные статьи (например ст. 240 КоАП).
 * Исходный текст вопроса сохраняется первой строкой.
 */
export function enrichQueryForRetrieval(question: string): string {
  const t = question.trim();
  const parts: string[] = [t];

  const workFinance =
    /бухгалтер|учёт|учет|финанс|компани|работодател|работаю|работник|организаци|хозяйств|счет|счёт/i.test(
      question,
    );
  const socialLeak =
    /соц\s*сет|интернет|пост|опублик|расскаж|вылож|в\s*сеть|утеч|мессенджер|чат|форум/i.test(
      question,
    );
  const liability =
    /грозит|штраф|наказан|ответственност|мрп|будет\s+ли|что\s+мне|какой\s+штраф/i.test(question);

  const adminKoapHint =
    /административн|коап|правонаруш|протокол|постановлен|инспектор|дпс|гибдд|полици|участков|патруль|эвакуатор|лишени[ея]\s+прав|трезвост|алкогол|наркот|курил|шум|мелкое\s+хулиганств/i.test(
      question,
    );

  if (workFinance || socialLeak) {
    parts.push(
      "разглашение сведений коммерческая тайна бухгалтерская информация КоАП статья 240 статья 185 налоговая тайна статья 473 служебная тайна охраняемая законом",
    );
  }
  if (liability && (workFinance || socialLeak)) {
    parts.push("административная ответственность штраф месячный расчетный показатель КоАП");
  }
  if (adminKoapHint) {
    parts.push(
      "Кодекс Республики Казахстан об административных правонарушениях КоАП РК административная ответственность штраф МРП",
    );
  }

  const witnessAdmin =
    /свидетел|показан|отказ|уклон|не\s*приду|не\s*прийду|неявк|по\s*вызову|вызов|допрос/i.test(
      question,
    );
  if (witnessAdmin) {
    parts.push(
      "КоАП статья 658 отказ уклонение свидетеля показания неявка без уважительных причин штраф два месячных расчетных показателя 2 МРП административное производство статья 754 свидетель процессуальные права обязанности",
    );
  }

  return parts.join("\n");
}
